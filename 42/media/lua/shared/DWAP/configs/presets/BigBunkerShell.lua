--- Reusable "big bunker" loot preset (the 100 loot entries shared by every
--- large military-bunker safehouse: configs 04, 10 and 12).
---
--- These three sites are the same underground template stamped at different
--- origins, so 100 of their loot squares are identical once expressed relative
--- to a shared origin. This module is the single source of truth for that
--- shared core. Each site's handful of site-specific squares (a different
--- books/media arrangement, a relocated tailoring bin, an essentials shelf in
--- a different spot) stays INLINE in the config, appended after this call.
---
--- The origin is the generator-CONTROLS square (config 04 {9947,12616,-4},
--- config 10 {13636,1262,-4}, config 12 {751,9812,-5}); every emitted entry's
--- coords = origin + (dx,dy,dz). z offsets are 0 here - the whole layout is on
--- the origin's floor.
---
--- Usage:
---   local BigBunkerShell = require("DWAP/configs/presets/BigBunkerShell")
---   local loot = BigBunkerShell({ x = 9947, y = 12616, z = -4 })
---   loot[#loot + 1] = { ... }  -- site-specific entries, origin-relative

