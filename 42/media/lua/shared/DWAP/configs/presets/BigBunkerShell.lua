-- Deep copy so the require-cached spec tables are never aliased into (or
-- mutated through) an emitted entry - dist and items are nested tables.
local function deepcopy(v)
    if type(v) ~= "table" then return v end
    local out = {}
    for k, val in pairs(v) do out[k] = deepcopy(val) end
    return out
end

--- @param origin table {x=,y=,z=} the generator-controls square.
--- @param overrides table|nil optional map keyed by spec id ("B1".."B100").
---        Each value is a PARTIAL field table shallow-merged onto that entry
---        after the defaults are applied. None of the current three sites need
---        one (their differences are inline extras, not tweaks to the shared
---        core), but the hook matches BunkerShell_17 for future sites.
--- @return table entries a fresh array of loot entries (new tables every call).
return function(origin, overrides)
    local out = {}
    for i = 1, #specs do
        local entry = deepcopy(specs[i])
        entry.coords = { x = origin.x + entry.dx, y = origin.y + entry.dy, z = origin.z + entry.dz }
        entry.dx, entry.dy, entry.dz = nil, nil, nil

        local ov = overrides and overrides[entry.id]
        if ov then
            for k, val in pairs(ov) do entry[k] = deepcopy(val) end
        end
        entry.id = nil

        out[i] = entry
    end
    return out
end
